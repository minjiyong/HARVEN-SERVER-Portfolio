SELECT t.name AS missing_table
FROM (
    SELECT 'User' AS name UNION ALL SELECT 'UserInventory' UNION ALL SELECT 'UserProgress' UNION ALL
    SELECT 'UserSkill' UNION ALL SELECT 'Guild' UNION ALL SELECT 'GuildMember' UNION ALL
    SELECT 'AuctionListing' UNION ALL SELECT 'AuctionSettlement' UNION ALL SELECT 'AuctionPriceHistory' UNION ALL
    SELECT 'EnchantFirstAchievement' UNION ALL SELECT 'EnchantGrace' UNION ALL
    SELECT 'GuildProgress' UNION ALL SELECT 'GuildLog' UNION ALL SELECT 'GuildPost' UNION ALL SELECT 'PlayerTransfer'
) t
LEFT JOIN information_schema.TABLES i ON i.TABLE_SCHEMA = 'GameServerDB' AND i.TABLE_NAME = t.name
WHERE i.TABLE_NAME IS NULL;

